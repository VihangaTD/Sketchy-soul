export const viewport: Viewport = {
  themeColor: '#0a0a0b',
  colorScheme: 'dark',
  width: 'device-width',
  initialScale: 1,
  // Never trap a visitor who needs to zoom in on a drawing.
  maximumScale: 5,
};

/**
 * The document shell, and nothing else.
 *
 * Everything a visitor sees around a page — header, footer, tab bar, cookie
 * banner, analytics — lives in the (site) group's layout instead, because the
 * admin panel is not a page of the website and must not inherit its chrome.
 * Its own header would otherwise sit under the public navigation, and the
 * studio would be counted in its own analytics.
 */
export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en" className={`${display.variable} ${sans.variable} ${mono.variable}`}>
      <head>
        {/* Cloudinary is on the critical path for every gallery image. */}
        <link rel="preconnect" href="https://res.cloudinary.com" crossOrigin="" />
      </head>
      <body className="min-h-dvh bg-black text-ivory antialiased">{children}</body>
    </html>
  );
}
