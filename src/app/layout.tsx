import type { Metadata, Viewport } from 'next';
import { Fraunces, JetBrains_Mono, Manrope } from 'next/font/google';
import './globals.css';

import { site, SITE_URL } from '@/lib/site';

/**
 * ── TYPEFACES ───────────────────────────────────────────────────────────────
 * All three are downloaded and self-hosted by next/font at build time: no
 * render-blocking request to fonts.googleapis.com, no layout shift, no
 * third-party cookie.
 *
 *   Fraunces        headings and display. A "soft serif" whose curves are
 *                   slightly irregular on purpose — it reads hand-made, which
 *                   is exactly what the studio sells.
 *   Manrope         body copy, buttons, forms, the admin panel. Humanist
 *                   geometry that stays legible at 11–13px on a dark
 *                   background, where thin geometric sans faces disappear.
 *   JetBrains Mono  order references (SS-7F3K2Q) and anything that gets read
 *                   aloud down a phone line — unambiguous 0/O and 1/l.
 *
 * To swap a family: change the import and the `variable` stays the same, so
 * nothing else in the codebase needs touching.
 * ────────────────────────────────────────────────────────────────────────── */
const display = Fraunces({
  subsets: ['latin'],
  style: ['normal', 'italic'],
  display: 'swap',
  variable: '--font-display',
  preload: true,
});

const sans = Manrope({
  subsets: ['latin'],
  display: 'swap',
  variable: '--font-sans',
  preload: true,
});

const mono = JetBrains_Mono({
  subsets: ['latin'],
  display: 'swap',
  variable: '--font-mono',
  // Only used for short reference codes, so it can load after first paint.
  preload: false,
});

